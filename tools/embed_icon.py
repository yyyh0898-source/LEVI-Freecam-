#!/usr/bin/env python3
"""Embed a PNG file as a C++ byte array header.

usage: embed_icon.py <icon.png> <out.hpp>
"""
import pathlib
import sys


def main(argv):
    if len(argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    data = pathlib.Path(argv[1]).read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        print(f"error: {argv[1]} is not a PNG file", file=sys.stderr)
        return 1
    lines = []
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i:i + 12])
        lines.append(f"    {chunk},")
    body = "\n".join(lines)
    out = (
        "// Generated by tools/embed_icon.py from mod/assets/icon.png. Do not edit.\n"
        "#pragma once\n\n"
        "namespace freecam::assets {\n\n"
        f"inline constexpr unsigned char kIconPng[] = {{\n{body}\n}};\n\n"
        "} // namespace freecam::assets\n"
    )
    pathlib.Path(argv[2]).write_text(out, encoding="utf-8")
    print(f"wrote {argv[2]} ({len(data)} bytes of PNG)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
